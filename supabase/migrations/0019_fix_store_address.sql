-- ============================================================
-- 0019: 修正门店地址中的乱码字符
--
-- 实测缺陷（真实浏览器验收）：全站页脚「到店信息」渲染为
--   「广州市增城区新塘镇国贸汇妖腰* 林梓·头疗美容养生」
-- 其中「妖腰」是无意义乱码，`*` 是当初留的铺位号占位符。
--
-- 根因：0004_seed.sql 顶部注释写着「地址：广州市增城区新塘镇国贸汇
-- （"*"处待补具体铺位号）」，但插入语句把注释性文字连同占位符
-- 一起写进了地址字段值，于是占位说明变成了顾客可见的门店地址。
--
-- SiteFooter 是会员端/员工端/后台共用的组件，因此该乱码出现在每一页，
-- 属顾客直接可见的品牌形象破损。
--
-- 本迁移只做数据订正，不改结构；0004 一并修正，保证全新环境重建时不再复现。
-- 条件写法保证可重复执行：仅当地址仍含乱码时才更新，避免覆盖日后
-- 掌柜手动补录的真实铺位号。
-- ============================================================

update public.stores
set address = '广州市增城区新塘镇国贸汇 · 林梓·头疗美容养生'
where address like '%妖腰%';

-- 防御性兜底：若还剩「*」占位符（无论前后文），一并清掉该占位符本身
update public.stores
set address = replace(address, '*', '')
where address like '%*%';
